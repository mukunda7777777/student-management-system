package com.sms.ui.util;

import com.sms.model.Marks;
import com.sms.model.Student;
import com.sms.service.MarksService;

import javax.swing.*;
import java.awt.*;
import java.awt.print.*;
import java.time.format.DateTimeFormatter;
import java.util.List;

/**
 * Handles printing of mark sheets and other reports via Java Print API.
 */
public class PrintUtils {

    private PrintUtils() {}

    /**
     * Prints a mark sheet for the given student with their marks list.
     */
    public static void printMarkSheet(Student student, List<Marks> marksList,
                                      Object[] summary, String examType) {
        PrinterJob job = PrinterJob.getPrinterJob();
        job.setJobName("Mark Sheet - " + student.getFullName());
        job.setPrintable((graphics, pageFormat, pageIndex) -> {
            if (pageIndex > 0) return Printable.NO_SUCH_PAGE;

            Graphics2D g2 = (Graphics2D) graphics;
            g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
            g2.translate(pageFormat.getImageableX(), pageFormat.getImageableY());

            float width = (float) pageFormat.getImageableWidth();
            int y = 0;

            // ── Header ───────────────────────────────────────
            g2.setColor(new Color(0x0F1B2D));
            g2.fillRect(0, y, (int) width, 60);
            g2.setColor(Color.WHITE);
            g2.setFont(new Font("Segoe UI", Font.BOLD, 20));
            g2.drawString("Student Management System", 20, y + 25);
            g2.setFont(new Font("Segoe UI", Font.PLAIN, 13));
            g2.drawString("Official Mark Sheet", 20, y + 45);
            y += 75;

            // ── Student Info ─────────────────────────────────
            g2.setColor(Color.BLACK);
            g2.setFont(new Font("Segoe UI", Font.BOLD, 13));
            g2.drawString("Student Name : " + student.getFullName(), 20, y);
            g2.drawString("Roll No.     : " + student.getRollNo(),   250, y);
            y += 20;
            g2.setFont(new Font("Segoe UI", Font.PLAIN, 12));
            g2.drawString("Course       : " + (student.getCourseName() != null ? student.getCourseName() : "-"), 20, y);
            g2.drawString("Exam Type    : " + examType,                250, y);
            y += 15;
            g2.setColor(new Color(0x00C8A0));
            g2.drawLine(20, y, (int) width - 20, y);
            y += 15;

            // ── Table Header ─────────────────────────────────
            g2.setColor(new Color(0x1A2942));
            g2.fillRect(20, y, (int) width - 40, 24);
            g2.setColor(new Color(0x00C8A0));
            g2.setFont(new Font("Segoe UI", Font.BOLD, 12));
            g2.drawString("Subject",          30, y + 16);
            g2.drawString("Max Marks",       280, y + 16);
            g2.drawString("Marks Obtained",  370, y + 16);
            g2.drawString("Grade",           490, y + 16);
            y += 30;

            // ── Table Rows ───────────────────────────────────
            g2.setFont(new Font("Segoe UI", Font.PLAIN, 12));
            boolean alt = false;
            for (Marks m : marksList) {
                g2.setColor(alt ? new Color(0xF5F7FA) : Color.WHITE);
                g2.fillRect(20, y - 14, (int) width - 40, 22);
                g2.setColor(Color.BLACK);
                g2.drawString(m.getSubjectName(),                       30, y);
                g2.drawString(String.valueOf(m.getMaxMarks()),         295, y);
                g2.drawString(String.format("%.1f", m.getMarksObtained()), 390, y);
                g2.drawString(MarksService.computeShortGrade(m.getPercentage()), 500, y);
                y += 24;
                alt = !alt;
            }

            // ── Summary ──────────────────────────────────────
            y += 10;
            g2.setColor(new Color(0x0D1A2E));
            g2.fillRect(20, y, (int) width - 40, 40);
            g2.setColor(Color.WHITE);
            g2.setFont(new Font("Segoe UI", Font.BOLD, 13));
            double obtained = (double) summary[0];
            double max      = (double) summary[1];
            double pct      = (double) summary[2];
            String grade    = MarksService.computeGrade(pct);
            g2.drawString(String.format("Total: %.1f / %.1f   |   Percentage: %.2f%%   |   Grade: %s",
                    obtained, max, pct, MarksService.computeShortGrade(pct)), 30, y + 26);
            y += 60;

            // ── Footer ───────────────────────────────────────
            g2.setColor(Color.GRAY);
            g2.setFont(new Font("Segoe UI", Font.ITALIC, 10));
            g2.drawString("Generated by Student Management System — " +
                    java.time.LocalDate.now().format(DateTimeFormatter.ofPattern("dd-MMM-yyyy")),
                    20, y);

            return Printable.PAGE_EXISTS;
        });

        if (job.printDialog()) {
            try {
                job.print();
            } catch (PrinterException ex) {
                JOptionPane.showMessageDialog(null,
                        "Printing failed: " + ex.getMessage(),
                        "Print Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }

    /**
     * Prints an attendance report for a student.
     * summary rows: Object[] {subjectName, total, present, percentage}
     */
    public static void printAttendanceReport(Student student, List<Object[]> summaryRows) {
        PrinterJob job = PrinterJob.getPrinterJob();
        job.setJobName("Attendance Report - " + student.getFullName());
        job.setPrintable((graphics, pageFormat, pageIndex) -> {
            if (pageIndex > 0) return Printable.NO_SUCH_PAGE;
            Graphics2D g2 = (Graphics2D) graphics;
            g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
            g2.translate(pageFormat.getImageableX(), pageFormat.getImageableY());

            float width = (float) pageFormat.getImageableWidth();
            int y = 0;

            // Header
            g2.setColor(new Color(0x0F1B2D));
            g2.fillRect(0, y, (int) width, 60);
            g2.setColor(Color.WHITE);
            g2.setFont(new Font("Segoe UI", Font.BOLD, 20));
            g2.drawString("Student Management System", 20, y + 25);
            g2.setFont(new Font("Segoe UI", Font.PLAIN, 13));
            g2.drawString("Attendance Report", 20, y + 45);
            y += 75;

            g2.setColor(Color.BLACK);
            g2.setFont(new Font("Segoe UI", Font.BOLD, 13));
            g2.drawString("Student  : " + student.getFullName(), 20, y);
            g2.drawString("Roll No. : " + student.getRollNo(),   280, y);
            y += 20;
            g2.setFont(new Font("Segoe UI", Font.PLAIN, 12));
            g2.drawString("Course   : " + (student.getCourseName() != null ? student.getCourseName() : "-"), 20, y);
            y += 20;

            // Table
            g2.setColor(new Color(0x1A2942));
            g2.fillRect(20, y, (int) width - 40, 24);
            g2.setColor(new Color(0x00C8A0));
            g2.setFont(new Font("Segoe UI", Font.BOLD, 12));
            g2.drawString("Subject",      30, y + 16);
            g2.drawString("Total",       270, y + 16);
            g2.drawString("Present",     340, y + 16);
            g2.drawString("Attendance%", 420, y + 16);
            y += 30;

            g2.setFont(new Font("Segoe UI", Font.PLAIN, 12));
            boolean alt = false;
            for (Object[] row : summaryRows) {
                g2.setColor(alt ? new Color(0xF5F7FA) : Color.WHITE);
                g2.fillRect(20, y - 14, (int) width - 40, 22);
                g2.setColor(Color.BLACK);
                g2.drawString(row[0].toString(), 30,  y);
                g2.drawString(row[1].toString(), 285, y);
                g2.drawString(row[2].toString(), 355, y);
                g2.drawString(row[3].toString(), 435, y);
                y += 24;
                alt = !alt;
            }

            y += 20;
            g2.setColor(Color.GRAY);
            g2.setFont(new Font("Segoe UI", Font.ITALIC, 10));
            g2.drawString("Generated by Student Management System — " +
                    java.time.LocalDate.now().format(DateTimeFormatter.ofPattern("dd-MMM-yyyy")), 20, y);
            return Printable.PAGE_EXISTS;
        });
        if (job.printDialog()) {
            try { job.print(); }
            catch (PrinterException ex) {
                JOptionPane.showMessageDialog(null, "Print error: " + ex.getMessage(),
                        "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }
}
